#!/usr/bin/env python3
"""End-to-end smoke of this skill's wrapper/config through verified, without apply."""
from __future__ import annotations

import argparse
import json
import os
import shutil
import subprocess
import tempfile
from pathlib import Path

SKIP = shutil.ignore_patterns("__pycache__", "*.pyc", ".git", ".agents", ".agent-state")


def run(argv: list[str], cwd: Path) -> dict:
    proc = subprocess.run(argv, cwd=cwd, capture_output=True, text=True, timeout=300)
    if proc.returncode != 0:
        raise RuntimeError(f"command failed ({proc.returncode}): {argv}\n{proc.stdout}\n{proc.stderr}")
    return json.loads(proc.stdout)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--skill-root", type=Path, required=True)
    args = parser.parse_args()
    source = args.skill_root.resolve()

    with tempfile.TemporaryDirectory(prefix="rtx3090-l1-smoke-") as directory:
        temp = Path(directory)
        canonical = temp / "canonical"
        project = temp / "project"
        state = temp / "state"
        canonical.mkdir()
        project.mkdir()
        shutil.copytree(source, canonical / source.name, ignore=SKIP)

        wrapper = canonical / source.name / "scripts" / "self_improvement.py"
        env_args = [
            "--project-root", str(project),
            "--canonical-home", str(canonical),
            "--state-dir", str(state),
        ]
        observation = temp / "observation.json"
        observation.write_text(json.dumps({
            "type": "technique",
            "skill_name": source.name,
            "pattern_key": "smoke.policy-marker",
            "source_trust": "project-owned",
            "scope": "portable-skill",
            "risk": "low",
            "observation": "A verified inert policy marker is needed for the smoke fixture.",
            "provenance": "Synthetic project-owned fixture generated by the skill smoke test.",
            "hypothesis": "Adding one inert comment to the policy reference preserves all behavior.",
            "applicability": "Only validates the proposal pipeline in a temporary canonical/project layout.",
            "evaluation_plan": "Run every configured validator and behavioral case; require zero regressions.",
            "proposed_changes": [{"path": "references/self-improvement.md", "operation": "replace"}],
            "evidence": [],
        }, indent=2) + "\n", encoding="utf8")

        recorded = run(["python3", str(wrapper), "record", *env_args, "--input", str(observation)], canonical / source.name)
        candidate_id = recorded["id"]
        staged = run(["python3", str(wrapper), "stage", *env_args, "--candidate", candidate_id], canonical / source.name)
        worktree = Path(staged["worktree"])
        policy = worktree / "references" / "self-improvement.md"
        policy.write_text(policy.read_text(encoding="utf8") + "\n<!-- self-improvement smoke fixture -->\n", encoding="utf8")
        evaluated = run(["python3", str(wrapper), "evaluate", *env_args, "--candidate", candidate_id], canonical / source.name)

        proposal = state
        evaluation_files = list(proposal.rglob(f"proposals/{candidate_id}/evaluation.json"))
        diff_files = list(proposal.rglob(f"proposals/{candidate_id}/proposal.diff"))
        candidate_files = list(proposal.rglob(f"candidates/{candidate_id}.json"))
        candidate = json.loads(candidate_files[0].read_text(encoding="utf8")) if candidate_files else {}
        result = {
            "ok": bool(
                evaluated.get("verified") is True
                and candidate.get("status") == "verified"
                and evaluation_files
                and diff_files
                and evaluated.get("checks", {}).get("validators_ok") is True
                and evaluated.get("checks", {}).get("candidate_all_pass") is True
                and evaluated.get("checks", {}).get("expanded_all_pass") is True
                and not (project / ".agents" / "skills").exists()
            ),
            "candidate_id": candidate_id,
            "status": candidate.get("status"),
            "verified": evaluated.get("verified"),
            "validators_ok": evaluated.get("checks", {}).get("validators_ok"),
            "candidate_all_pass": evaluated.get("checks", {}).get("candidate_all_pass"),
            "expanded_all_pass": evaluated.get("checks", {}).get("expanded_all_pass"),
            "proposal_written": bool(evaluation_files and diff_files),
            "active_project_untouched": not (project / ".agents" / "skills").exists(),
            "reasons": evaluated.get("reasons", []),
        }
        print(json.dumps(result, indent=2, sort_keys=True))
        return 0 if result["ok"] else 1


if __name__ == "__main__":
    raise SystemExit(main())
